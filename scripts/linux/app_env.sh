#!/bin/sh

APP_LINUX_NAME=""
APP_LINUX_VERSION=""
APP_LINUX_BUILD_VERSION=""

CAKEWALLET="cakewallet"
TWALLET="twallet"

TYPES=($TWALLET $CAKEWALLET)
APP_LINUX_TYPE=$TWALLET

if [ -n "$1" ]; then
	APP_LINUX_TYPE=$1
fi

CAKEWALLET_NAME="Cake Wallet"
CAKEWALLET_VERSION="6.5.0"
CAKEWALLET_BUILD_NUMBER=84

TWALLET_NAME="T-Wallet"
TWALLET_VERSION="1.0.0"
TWALLET_BUILD_NUMBER=1

if ! [[ " ${TYPES[*]} " =~ " ${APP_LINUX_TYPE} " ]]; then
    echo "Wrong app type."
    exit 1
fi

case $APP_LINUX_TYPE in
	$TWALLET)
		APP_LINUX_NAME=$TWALLET_NAME
		APP_LINUX_VERSION=$TWALLET_VERSION
		APP_LINUX_BUILD_NUMBER=$TWALLET_BUILD_NUMBER;;
	$CAKEWALLET)
		APP_LINUX_NAME=$CAKEWALLET_NAME
		APP_LINUX_VERSION=$CAKEWALLET_VERSION
		APP_LINUX_BUILD_NUMBER=$CAKEWALLET_BUILD_NUMBER;;
esac

export APP_LINUX_TYPE
export APP_LINUX_NAME
export APP_LINUX_VERSION
export APP_LINUX_BUILD_NUMBER
